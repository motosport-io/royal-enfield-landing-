#!/usr/bin/env python3
"""Builds terms.html and privacy.html from the approved texts in docs/legal/*.md.

The legal wording lives only in the .md files and is copied word for word; this script
adds markup only (headings, paragraphs, bullet lists, mailto:/tel: links).
Run from the repository root after editing a text:  python3 scripts/build-legal.py
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = {
    'terms': {'title': 'תנאי שימוש', 'other': ('privacy', 'מדיניות פרטיות')},
    'privacy': {'title': 'מדיניות פרטיות', 'other': ('terms', 'תנאי שימוש')},
}
EMAIL = re.compile(r'[\w.+-]+@[\w-]+(?:\.[\w-]+)+')
PHONE = re.compile(r'\b0\d{1,2}-\d{7}\b')


def inline(text):
    out = html.escape(text, quote=False)
    out = EMAIL.sub(lambda m: f'<a href="mailto:{m.group(0)}" dir="ltr">{m.group(0)}</a>', out)
    out = PHONE.sub(lambda m: f'<a href="tel:{m.group(0).replace("-", "")}" dir="ltr">{m.group(0)}</a>', out)
    return out


def body_html(md):
    parts, items = [], []

    def flush():
        if items:
            parts.append('      <ul>\n' + ''.join(f'        <li>{inline(i)}</li>\n' for i in items) + '      </ul>')
            items.clear()

    for line in md.splitlines():
        line = line.strip()
        if not line:
            flush()
        elif line.startswith('### '):
            flush()
            parts.append(f'      <h2>{inline(line[4:])}</h2>')
        elif line.startswith('## '):
            flush()  # page title: rendered as the <h1> by the template
        elif line.startswith('- '):
            items.append(line[2:])
        else:
            flush()
            parts.append(f'      <p>{inline(line)}</p>')
    flush()
    return '\n'.join(parts)


TEMPLATE = """<!doctype html>
<html lang="he" dir="rtl">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>{title} | Royal Enfield ישראל</title>
  <meta name="theme-color" content="#102b46">
  <link rel="stylesheet" href="/assets/css/fonts.css">
  <link rel="stylesheet" href="/assets/css/styles.css">
</head>
<body class="legal-page">
  <!-- Generated by scripts/build-legal.py from docs/legal/{slug}.md – edit the .md file, not this page -->
  <a class="skip-link" href="#content">דילוג לתוכן העמוד</a>

  <header class="legal-header">
    <a class="legal-header__logo" href="/"><img src="/assets/images/brand/royal-enfield-logo.png" width="140" height="72" alt="Royal Enfield – חזרה לדף הנחיתה" lang="en"></a>
    <a href="/">חזרה לדף הנחיתה</a>
  </header>

  <main class="legal" id="content" tabindex="-1">
    <h1>{title}</h1>
    <div class="legal__body">
{body}
    </div>
    <p class="legal__back"><a href="/">חזרה לדף הנחיתה</a></p>
  </main>

  <footer class="footer legal-footer">
    <h2 class="sr-only">מידע נוסף</h2>
    <div class="footer__legal">
      <ul class="footer__links">
        <li><a href="/">דף הנחיתה</a></li>
        <li><a href="/terms"{terms_current}>תנאי שימוש</a></li>
        <li><a href="/privacy"{privacy_current}>מדיניות פרטיות</a></li>
        <li><a href="/#cookies">הגדרות עוגיות</a></li>
      </ul>
    </div>
  </footer>
</body>
</html>
"""

for slug, page in PAGES.items():
    md = (ROOT / 'docs' / 'legal' / f'{slug}.md').read_text(encoding='utf-8')
    out = TEMPLATE.format(
        title=page['title'],
        slug=slug,
        body=body_html(md),
        terms_current=' aria-current="page"' if slug == 'terms' else '',
        privacy_current=' aria-current="page"' if slug == 'privacy' else '',
    )
    (ROOT / f'{slug}.html').write_text(out, encoding='utf-8')
    print('wrote', f'{slug}.html')
